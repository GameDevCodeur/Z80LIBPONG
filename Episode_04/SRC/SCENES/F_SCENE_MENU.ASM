INCLUDE "../PONG/MENU/F_COLOR_FLASH_EFFECT.ASM"

F_SCENE_MENU_INITIALISATION

	; Eteindre ecran
	CALL F_ETEINDRE_ENCRES 

	; Nettoyer ecran
	LD   HL, #C000
	mCLEAR_BUFFER (VOID)

	; Afficher titre PONG
 	LD   HL, SCR_MENU_ZX0
 	LD   DE, #C000
 	CALL F_ZX0_DECOMPRESS

 	; Afficher 'PRESS KEY TO START'
 	mAFFICHER_CHAR_4xB FNT_P, TXT_MENU_VRAM+00, TXT_NBL
 	mAFFICHER_CHAR_4xB FNT_R, TXT_MENU_VRAM+02, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_E, TXT_MENU_VRAM+04, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_S, TXT_MENU_VRAM+06, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_S, TXT_MENU_VRAM+08, TXT_NBL
	
	mAFFICHER_CHAR_4xB FNT_K, TXT_MENU_VRAM+12, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_E, TXT_MENU_VRAM+14, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_Y, TXT_MENU_VRAM+16, TXT_NBL
	
	mAFFICHER_CHAR_4xB FNT_T, TXT_MENU_VRAM+20, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_O, TXT_MENU_VRAM+22, TXT_NBL
	
	mAFFICHER_CHAR_4xB FNT_S, TXT_MENU_VRAM+26, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_T, TXT_MENU_VRAM+28, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_A, TXT_MENU_VRAM+30, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_R, TXT_MENU_VRAM+32, TXT_NBL
	mAFFICHER_CHAR_4xB FNT_T, TXT_MENU_VRAM+34, TXT_NBL

	; Allumer ecran
 	LD   HL, SCR_MENU_PAL
    LD   BC, GA_PORT
    LD   A, PAL_NBE
    mGA_SET_PALETTE (VOID)
        
RET

F_SCENE_MENU

	CALL F_COLOR_FLASH_EFFECT
    mKEY_ANY_REQUESTED (VOID) : RET Z

    LD   B, ID_SCENE_JEU  
    JP   F_CHANGER_SCENE_JEU

