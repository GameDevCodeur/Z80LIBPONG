
; HL DEST 
; DE FNT

F_SCORE_AFFICHER
	LD   C, GLIPH_HEIGHT
	LD   A, (DE)

NEXTLINE
	PUSH HL              	; on mémorise le début de cette ligne
	LD   B, GLIPH_WIDTH
	
BIT_NEXT	
	RRCA
	LD   (HL), PATERN_BLACK
	JR   NC, SKIP
	LD   (HL), PATERN_WHITE
SKIP
	INC  HL
	DJNZ BIT_NEXT

	POP  HL
	mSET_NEXTLINE_HL (VOID)
	INC  DE

	LD   A, (DE)

	DEC  C
	JR   NZ, NEXTLINE

	RET

PATERN_WHITE EQU #3C
PATERN_BLACK EQU 0

GLIPH_HEIGHT EQU 15
GLIPH_WIDTH  EQU 4

